'use strict';
const fs=require('node:fs'),vm=require('node:vm'),assert=require('node:assert/strict');
const source=fs.readFileSync(__dirname+'/TEST_TH300.cjs','utf8');
const prefix=source.slice(0,source.indexOf("test('holding 305"));
assert(prefix.includes('function harness('));
const ctx={require,__dirname,console};
vm.runInNewContext(prefix+'\nglobalThis.make=harness;',ctx);
const q=ctx.make({fastReady:true,defaultDistance:true,newDefault:true,startX:310});
let kind='THIEN_QUAN';
q.W.KVPV_FAR_SCOPE={status:()=>({kind}),inside:()=>kind==='THIEN_QUAN',eligible:()=>true};
q.W.KVPV_TQ_POSITION_ONLY={enabled:true,distance:310,heal:false};
q.W._Ba._Co._Mo.ins.curLv=4100;
q.s._rtt=[[1001,0,50],[8001,0,50],[8005,0,50]];
q.s._wet=[];
q.c._jh={isPlaying:true};
q.mod.setInterleaved(true,310);
q.mod.setTianQuanFiveBasics(true,10);
q.mod.setTianQuanTuyetHoc(true);
q.mod.setTianQuan4100BasicSolo(false);
q.mod.start('SCAN');
const baseline=q.calls.length;
q.advance(30);
assert.equal(q.calls.length,baseline,'native animation must gate while opt-in disabled');
q.mod.setTianQuan4100SkipAnimation(true);
assert.equal(q.mod.status(false).animation4100.active,true);
assert.equal(q.mod.status(false).paceMs,10);
for(let i=0;i<12;i++)q.advance(10);
const casted=q.calls.slice(baseline);
assert(casted.some(x=>x===1001),'TH cast can pass while native animation is playing');
assert(casted.some(x=>x===8001||x===8005),'basic cast can fill post-TH animation gap');
assert(q.mod.status(false).animation4100.admittedWhilePlaying>0,'counter proves gate skip used');
const beforeCooldown=q.calls.length;
q.cooldown(true);q.advance(100);
assert.equal(q.calls.length,beforeCooldown,'native component cooldown still blocks animation bypass');
q.cooldown(false);
const nativeCooldown=q.c.isCooldown;
q.c.isCooldown=undefined;q.advance(100);
assert.equal(q.calls.length,beforeCooldown,'missing native cooldown API blocks animation bypass');
q.c.isCooldown=nativeCooldown;
q.W._Ba._Co._Mo.ins.curLv=4101;q.advance(100);
assert.equal(q.mod.status(false).animation4100.active,false);
assert.equal(q.calls.length,beforeCooldown,'floor 4101 preserves native animation gate');
q.W._Ba._Co._Mo.ins.curLv=4100;kind='LINH_LUNG';q.advance(100);
assert.equal(q.calls.length,beforeCooldown,'other map preserves animation gate');
kind='THIEN_QUAN';
q.mod.setTianQuan4100SkipAnimation(false);
q.advance(100);
assert.equal(q.calls.length,beforeCooldown,'turning off restores native animation readiness');
assert.deepEqual(Array.from(q.s._rtt.map(row=>row[2])),[50,50,50],'original native cooldown durations unchanged');
q.mod.stop();
console.log('PASS TQ4100 10ms TH+basics: client animation gate skip, native cooldown, non-4100 isolation and disable restoration.');
