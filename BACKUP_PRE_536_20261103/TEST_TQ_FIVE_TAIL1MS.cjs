q.mod.setTianQuanTuyetHoc(true);q.mod.setConfirmedTailCut(true);q.mod.start('SCAN');q.pump();
let cuts=0;q.c._jh={isPlaying:true,stop(){cuts++}};
q.advance(2);assert.equal(cuts,0,'TH animation is not cut without a matching basic hit');
assert.equal(q.mod.status(false).distanceOnly310,true);
assert.equal(q.mod.status(false).recoveryEnabled,false);
q.mod.stop();
console.log('PASS TQ five basics: 1ms client cadence, confirmed-hit-only animation tail, native cooldown respected, TH protected, 310 no heal');
