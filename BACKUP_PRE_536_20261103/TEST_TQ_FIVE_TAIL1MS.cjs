'use strict';
const assert=require('node:assert/strict'),fs=require('node:fs'),vm=require('node:vm');
const suite=fs.readFileSync(__dirname+'/TEST_TH300.cjs','utf8');
const prefix=suite.slice(0,suite.indexOf("test('holding 305"));
assert(prefix.includes('function harness('),'test harness is still available');
const ctx={require,__dirname,console};
vm.runInNewContext(prefix+'\nglobalThis.make=harness;',ctx);
const actor='10228867268946';
for(const id of [8001,8002,8003,8004,8005]){
  const q=ctx.make({fastReady:true,defaultDistance:true,newDefault:true,startX:310});
  q.W.KVPV_FAR_SCOPE={status:()=>({kind:'THIEN_QUAN'}),inside:()=>true,eligible:()=>true};
  q.s._rtt=[[id,0,50]];q.s._wet=[];
  let trimmed=0,locked=false;
  const tween=()=>({isPlaying:true,stop(){this.isPlaying=false;trimmed++;}});
  q.c.isCooldown=()=>locked||q.c._jh?.isPlaying===true;
  q.mod.setInterleaved(true,310);
  q.mod.setTianQuanFiveBasics(true,1);
  q.mod.setTianQuanTuyetHoc(false);
  q.mod.setConfirmedTailCut(true);
  q.mod.start('SCAN');q.pump();
  assert.deepEqual(Array.from(q.calls),[id]);
  assert.equal(q.mod.status(false).paceMs,1);
  assert.equal(q.mod.status(false).goalDistance,310);
  assert.equal(q.mod.status(false).recoveryEnabled,true,'harness without TQ position-only policy keeps native compatibility');
  assert.deepEqual(Array.from(q.mod.status(false).confirmedTailSkillIds),[8001,8002,8003,8004,8005]);
  q.c._jh=tween();q.advance(2);
  assert.equal(trimmed,0,'no tail cut before confirmed hit for '+id);
  const hitsBefore=q.mod.status(false).confirmedBasicTailCuts;
  locked=true;
  q.events[1012](actor,id*10000,10,1,'boss1');
  const castsBefore=q.calls.length;
  q.advance(2);
  assert.equal(trimmed,1,'confirmed basic should release animation tail for '+id);
  assert.equal(q.mod.status(false).confirmedBasicTailCuts,hitsBefore+1);
  assert.equal(q.calls.length,castsBefore,'native cooldown still blocks new casts for '+id);
  q.advance(2);assert.equal(trimmed,1,'cut once per cast');
  locked=false;q.advance(2);assert(q.calls.length>castsBefore,'native-ready basic can resume for '+id);
  q.mod.stop();
}
const q=ctx.make({fastReady:true,defaultDistance:true,newDefault:true,startX:310});
